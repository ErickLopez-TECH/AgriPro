    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        // 1. Obtener el id: si está vacío se asigna automático, si no, debe ser numérico
        int id = 0;
        if (txtId.getText().equals("")){
            id = misMetodos.siguienteUser();
        } else{
            id = Integer.parseInt(txtId.getText());
        }

        
        String cedula = txtCedula.getText().trim();
        String nombre = txtNombre.getText().trim();
        String nombreUser = txtUser.getText().trim();
        String clave = new String(pswClave.getPassword());
        int rol = cmbRol.getSelectedIndex();
        int estado = cmbEstado.getSelectedIndex(); // 0:Inactivo | 1:Activo

        // 2. Validar campos
        //String error = misMetodos.validarEmpleado(cedula, nombre, apellido1, apellido2, telefono, direccion);
        if (txtCedula.getText().isEmpty()){
            JOptionPane.showMessageDialog(null, "Vacio", "Aviso Importante", JOptionPane.WARNING_MESSAGE);
            return;
        }
       /* if (misMetodos.cedulaDuplicada(cedula, id)){
            JOptionPane.showMessageDialog(null, "Ya existe un empleado con esa cédula", "Aviso Importante", JOptionPane.WARNING_MESSAGE);
            return;
        }*/

        // 3. Crear o modificar
        ObjUsuario miuser = new ObjUsuario(id, cedula, nombre, nombreUser, clave, rol, estado);
        int indice = misMetodos.buscarUserId(id);

        if (indice == -1){
            miuser.setId(misMetodos.siguienteUser());
            almacen.agregarUser(miuser);
            JOptionPane.showMessageDialog(null, "Empleado agregado correctamente");
            
            movimiento = "Agrego";
            
        } else{
            almacen.editarUser(indice, miuser);
            JOptionPane.showMessageDialog(null, "Empleado modificado correctamente");
            
            movimiento = "Edito";
        }

        
        tblEmpleados.setModel(almacen.mostrarUser());
        arch.escribeUsuarios();
        
        
    }//GEN-LAST:event_btnGuardarActionPerformed

