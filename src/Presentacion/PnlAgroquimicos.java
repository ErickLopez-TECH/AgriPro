    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        //Obtiene el id y si está vacío se asigna automaticamente
        int id = 0;
        if (txtId.getText().equals("")){
            id = misMetodos.siguienteAgroquimico();
        } else{
            id = Integer.parseInt(txtId.getText());
        }

        //Capturaa los datos digitados
        String nombre = txtNombreComercial.getText().trim();
        String reactivo = txtReactivo.getText().trim();
        String presentacion = txtPresentacion.getText().trim();
        String dosis = txtDosis.getText().trim();
        String tipo = cmbTipo.getSelectedItem().toString(); //el texto del tipo, no su posición
        int estado = cmbEstado.getSelectedIndex(); //0 = Inactivo | 1 = Activo

        //Valida los campos (si hay error se muestra el mensaje y se detiene)
        String error = misMetodos.validarAgroquimico(nombre, reactivo, presentacion, dosis, tipo);
        if (!error.equals("")){
            JOptionPane.showMessageDialog(null, error, "Aviso Importante", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (misMetodos.nombreDuplicado(nombre, id)){
            JOptionPane.showMessageDialog(null, "Ya existe un agroquímico con ese nombre comercial", "Aviso Importante", JOptionPane.WARNING_MESSAGE);
            return;
        }

        //Crear o modificar
        double dosisHectarea = Double.parseDouble(dosis); //ya se validó que es un número mayor que cero
        ObjAgroquimico miAgro = new ObjAgroquimico(id, nombre, reactivo, presentacion, dosisHectarea, tipo, estado);
        int indice = misMetodos.buscarAgroquimico(id);

        if (indice == -1){
            miAgro.setId(misMetodos.siguienteAgroquimico());
            almacen.agregarAgroquimico(miAgro);
            JOptionPane.showMessageDialog(null, "Agroquímico agregado correctamente");
        } else{
            almacen.editarAgroquimico(indice, miAgro);
            JOptionPane.showMessageDialog(null, "Agroquímico modificado correctamente");
        }

        //Guarda en el archivo JSON y refrescar la pantalla
        arch.escribeAgroquimicos();
        tblAgroquimicos.setModel(almacen.mostrarAgroquimico());
        limpiarCampos();
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActionPerformed
        // TODO add your handling code here:
        //Revisa que haya un agroquímico seleccionado o buscado
        if (txtId.getText().equals("")){
            JOptionPane.showMessageDialog(null, "Seleccione o busque un agroquímico para borrar", "Aviso Importante", JOptionPane.WARNING_MESSAGE);
            return;
        }

        //Busca su posición en la lista (-1 si no existe)
        int indice = misMetodos.buscarAgroquimico(Integer.parseInt(txtId.getText().trim()));

        if (indice == -1){
            JOptionPane.showMessageDialog(null, "No existe un agroquímico con esa identificación", "Aviso Importante", JOptionPane.WARNING_MESSAGE);
            return;
        }

        //Pide confirmación antes de borrar
        int respuesta = JOptionPane.showConfirmDialog(null, "Desea borrar este agroquimico?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (respuesta == JOptionPane.YES_OPTION){
            almacen.quitarAgroquimico(indice);
            arch.escribeAgroquimicos();
            tblAgroquimicos.setModel(almacen.mostrarAgroquimico());
            limpiarCampos();
            JOptionPane.showMessageDialog(null, "Agroquimico borrado correctamente");
        }
    }//GEN-LAST:event_btnBorrarActionPerformed

