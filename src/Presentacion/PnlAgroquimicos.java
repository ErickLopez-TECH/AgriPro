    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        //Revisa que se haya digitado un id
        if (txtId.getText().equals("")){
            JOptionPane.showMessageDialog(null, "Digite la identificación del agroquímico a buscar", "Aviso Importante", JOptionPane.WARNING_MESSAGE);
            return;
        }

        //Busca el objeto por id (devuelve null si no existe)
        int id = Integer.parseInt(txtId.getText().trim());
        ObjAgroquimico miAgro = misMetodos.buscarObjAgroquimico(id);

        //Muestra el resultado
        if (miAgro == null){
            JOptionPane.showMessageDialog(null, "No existe un agroquímico con esa identificación", "Aviso Importante", JOptionPane.WARNING_MESSAGE);
        } else{
            cargarAgroquimico(miAgro);
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

