    private void tblDatosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblDatosMouseClicked

        //--Click en una fila se cargan sus datos
        int fila = tblDatos.getSelectedRow();
        if (fila != -1) {
            ObjCultivo miCultivo = almacen.listarCultivo().get(fila);
            txtId.setText(String.valueOf(miCultivo.getId()));
            txtNombre.setText(miCultivo.getNombreComer());
            txtNombreCientifico.setText(miCultivo.getNombreCientifico());
            cmbEstado.setSelectedIndex(miCultivo.getEstado());
        }
    }//GEN-LAST:event_tblDatosMouseClicked

    private void btnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActionPerformed

        //--Borrar el cultivo por Id
        if (!txtId.getText().equals("")) {
            int id = Integer.parseInt(txtId.getText());
            int indice = misMetodos.buscarCultivo(id);
            if (indice != -1) {
                almacen.quitarzCultivo(indice);
                arch.escribeCultivos();
                tblDatos.setModel(almacen.mostrarCultivo());
            }
        }
    }//GEN-LAST:event_btnBorrarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

        //--Valida que no haya campos vacíos
        if (txtNombre.getText().equals("") || txtNombreCientifico.getText().equals("")) {
            JOptionPane.showMessageDialog(null, "Debe digitar el nombre comercial y el nombre científico",
                    "Aviso Importante", JOptionPane.WARNING_MESSAGE);
        } else {
            //--Si no se digitan el Id, se asigna el siguiente
            int id = 0;
            if (txtId.getText().equals("")) {
                id = misMetodos.siguienteCultivo();
            } else {
                id = Integer.parseInt(txtId.getText());
            }
            //--Carga los valores de la interfaz
            String nombre = txtNombre.getText();
            String nombreCientifico = txtNombreCientifico.getText();
            int estado = cmbEstado.getSelectedIndex(); //--0 Inactivo / 1 Activo

            ObjCultivo miCultivo = new ObjCultivo(id, nombre, nombreCientifico, estado);

            //--Insertar o modificar
            int indice = misMetodos.buscarCultivo(id);

            if (indice == -1) {
                miCultivo.setId(misMetodos.siguienteCultivo());
                almacen.agregarCultivo(miCultivo);
            } else {
                almacen.editarCultivo(indice, miCultivo);
            }
            //--Guarda en el archivo y refresca la tabla
            arch.escribeCultivos();

            tblDatos.setModel(almacen.mostrarCultivo());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed

        //--Buscar el cultivo por Id y mostrar sus datos
        if (!txtId.getText().equals("")) {
            int id = Integer.parseInt(txtId.getText());
            int indice = misMetodos.buscarCultivo(id);
            if (indice != -1) {
                ObjCultivo miCultivo = almacen.listarCultivo().get(indice);
                txtNombre.setText(miCultivo.getNombreComer());
                txtNombreCientifico.setText(miCultivo.getNombreCientifico());
                cmbEstado.setSelectedIndex(miCultivo.getEstado());
            }
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

